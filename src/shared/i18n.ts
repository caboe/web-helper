export const translations: Record<Locale, Messages> = { de, en, fr, es, zh }

export function localeLabel(locale: Locale): string {
  return LOCALES.find((l) => l.code === locale)?.label ?? locale
}

/** Erkennt die Sprache aus den Browsereinstellungen (navigator.languages), Fallback: de. */
export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'de'
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const raw of langs) {
    const code = String(raw).toLowerCase()
    if (code.startsWith('de')) return 'de'
    if (code.startsWith('fr')) return 'fr'
    if (code.startsWith('es')) return 'es'
    if (code.startsWith('zh')) return 'zh'
    if (code.startsWith('en')) return 'en'
  }
  return 'de'
}

export function t(locale: Locale, key: MessageKey, vars?: Vars): string {
  let s: string = translations[locale]?.[key] ?? translations.de[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v))
    }
  }
  return s
}